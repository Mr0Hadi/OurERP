/**
 * مانده‌ی کلِ یک طرف حساب = مانده‌ی دفترِ حسابِ اشخاص (`ledgerBalance`).
 * مانده‌ی دستیِ فرم از ۲۰۲۶-۱۰-۳۰ خودش ردیفِ «مانده‌ی اول دوره» در دفتر است
 * (ویرایشش تفاوت را می‌نویسد)، پس دوباره جمع زده نمی‌شود. مثبت یعنی طرف به
 * ما بدهکار است.
 */
export function partyBalanceOf(party) {
  return Number(party?.ledgerBalance) || 0;
}
