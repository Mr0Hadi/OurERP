// src/shared/store/formDraftStore.js
import { create } from "zustand";

/**
 * پیش‌نویسِ فرم‌هایی که کاربر وسطِ پرکردنشان به یک صفحه‌ی دیگر می‌رود.
 *
 * الگو همان چیزی است که در «ثبت خرید جدید» کار می‌کند: از فرمِ خرید
 * می‌شود به «تامین‌کننده جدید» رفت و برگشت بدون اینکه سبد خرید پاک شود.
 * تفاوت اینجاست که آن فیچر یک استورِ اختصاصیِ کاملِ فرم دارد؛ فرم‌های
 * کارمند و واحد و تیم آن‌قدر کوچک‌اند که ساختنِ سه استورِ جدا فقط تکرار
 * می‌شد.
 *
 * قرارداد عمدی: پیش‌نویس **یک‌بارمصرف** است — `useFormDraft` هنگام mount
 * می‌خواندش و بلافاصله پاک می‌کند، پس اگر کاربر فرم را رها کند و بعداً از
 * جای دیگری برگردد، با یک فرمِ کهنه روبه‌رو نمی‌شود.
 *
 * کلید را خودِ صفحه می‌سازد و باید شاملِ شناسه باشد
 * (`"department:5"`)، وگرنه پیش‌نویسِ یک رکورد روی رکوردِ دیگر می‌نشیند.
 */
export const useFormDraftStore = create((set) => ({
  drafts: {},

  saveDraft: (key, values) =>
    set((state) => ({ drafts: { ...state.drafts, [key]: values } })),

  clearDraft: (key) =>
    set((state) => {
      const rest = { ...state.drafts };
      delete rest[key];
      return { drafts: rest };
    }),
}));
