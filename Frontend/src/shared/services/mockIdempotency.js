/**
 * تکه‌ی ایدمپوتنسیِ سمتِ mock.
 *
 * لایه‌ی mock امروز نقشِ سرور را بازی می‌کند، پس قاعده‌ای که سرور باید
 * رعایت کند باید همین‌جا هم رعایت شود — وگرنه رفتارِ اپ قبل و بعد از
 * مهاجرت فرق می‌کند و باگ فقط روزِ سوییچ پیدا می‌شود.
 *
 * چرا لازم است: عملیات‌های نوشتنِ مرجوعی تجمعی‌اند («۳ عدد دریافت شد»
 * روی مقدارِ قبلی اضافه می‌شود). یک دوبار-کلیک یا retry، بدون این
 * محافظ، موجودی یا مبلغ فاکتور را دوبار جابه‌جا می‌کند.
 *
 * نگه‌داری در حافظه است و با رفرشِ صفحه پاک می‌شود؛ برای نقشِ mock کافی
 * است. سرور باید همین را با ذخیره‌سازیِ ماندگار پیاده کند.
 */

const results = new Map();

export async function runOnce(key, fn) {
  if (!key) return fn();
  if (results.has(key)) return results.get(key);

  // خودِ Promise ذخیره می‌شود نه نتیجه‌اش، تا دو فراخوانیِ هم‌زمان با یک
  // کلید هم به یک اجرا برسند، نه دو تا.
  const promise = fn().catch((error) => {
    // خطا کش نمی‌شود: تلاش دوباره با همان کلید باید واقعاً دوباره اجرا
    // شود، چون عملیاتِ قبلی اثری نگذاشته.
    results.delete(key);
    throw error;
  });

  results.set(key, promise);
  return promise;
}
